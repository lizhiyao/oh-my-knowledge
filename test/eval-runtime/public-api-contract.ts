/** 从 dist 的 .d.ts 提取命名导出，区分值导出与类型导出。 */
export function declarationExports(entry: string): { values: string[]; types: string[] } {
  const file = resolve(`dist/eval-runtime/${entry}.d.ts`);
  if (!existsSync(file)) throw new Error(`缺少 ${file}；请先运行 yarn build。`);
  const source = ts.createSourceFile(
    file,
    readFileSync(file, 'utf8'),
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );
  const values: string[] = [];
  const types: string[] = [];
  for (const statement of source.statements) {
    if (!ts.isExportDeclaration(statement)
        || statement.exportClause === undefined
        || !ts.isNamedExports(statement.exportClause)) continue;
    for (const element of statement.exportClause.elements) {
      (statement.isTypeOnly || element.isTypeOnly ? types : values).push(element.name.text);
    }
  }
  return { values: values.sort(), types: types.sort() };
}

/**
 * 从 src 的 .ts 入口提取命名导出的名字集合（不区分值/类型）。
 *
 * 与 declarationExports 共用 AST 解析，但读 src 而非 dist，因此无需 build。
 * 值/类型分类仍由 dist 的 .d.ts 层校验；src 层只保证导出名齐全。
 */
export function sourceExportNames(entry: string): string[] {
  const file = resolve(`src/eval-runtime/${entry}.ts`);
  if (!existsSync(file)) throw new Error(`缺少 ${file}。`);
  const source = ts.createSourceFile(
    file,
    readFileSync(file, 'utf8'),
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );
  const names: string[] = [];
  for (const statement of source.statements) {
    if (!ts.isExportDeclaration(statement)
        || statement.exportClause === undefined
        || !ts.isNamedExports(statement.exportClause)) continue;
    for (const element of statement.exportClause.elements) {
      names.push(element.name.text);
    }
  }
  return names.sort();
}
